import java.sql.*;
import java.nio.file.*;
import java.nio.charset.StandardCharsets;
import java.util.*;
/** Read-only export of the isolated DM demo schema, never original SYSDBA users. */
public class ExportPostgresDemo {
 static String q(String id) { if(!id.matches("[A-Za-z0-9_]+"))throw new IllegalArgumentException(id);return "\""+id.toLowerCase(Locale.ROOT)+"\""; }
 static String type(ResultSetMetaData m,int i,boolean identity) throws SQLException {
  if(identity)return "integer GENERATED BY DEFAULT AS IDENTITY";
  switch(m.getColumnType(i)) {
   case Types.CHAR:case Types.NCHAR:case Types.VARCHAR:case Types.NVARCHAR:return "varchar("+Math.max(1,m.getPrecision(i))+")";
   case Types.INTEGER:case Types.SMALLINT:case Types.TINYINT:return "integer";
   case Types.BIGINT:return "bigint";
   case Types.NUMERIC:case Types.DECIMAL:return "numeric";
   case Types.FLOAT:case Types.DOUBLE:case Types.REAL:return "double precision";
   case Types.DATE:return "date";
   case Types.TIMESTAMP:return "timestamp without time zone";
   case Types.BOOLEAN:case Types.BIT:return "boolean";
   case Types.LONGVARCHAR:case Types.CLOB:return "text";
   default:throw new IllegalStateException("Unsupported JDBC type "+m.getColumnType(i));
  }
 }
 static String literal(ResultSet rows,ResultSetMetaData m,int i) throws Exception {
  Object value=rows.getObject(i); if(value==null)return "NULL";
  if(value instanceof Number)return value.toString();
  if(value instanceof Boolean)return value.toString();
  String text=rows.getString(i);
  if(m.getColumnType(i)==Types.CHAR||m.getColumnType(i)==Types.NCHAR)text=text.replaceFirst(" +$", "");
  if(text.indexOf(0)>=0)throw new IllegalStateException("NUL character in source data");
  return "'"+text.replace("'", "''")+"'";
 }
 public static void main(String[] args) throws Exception {
  Class.forName("dm.jdbc.driver.DmDriver");
  StringBuilder sql=new StringBuilder("BEGIN;\nSET standard_conforming_strings = on;\n");
  StringBuilder report=new StringBuilder("# PostgreSQL demo snapshot\n\nSource: isolated local DEMO_APP, read-only. Original SYSDBA.USERS excluded.\n\n");
  int total=0;
  try(Connection c=DriverManager.getConnection("jdbc:dm://127.0.0.1:5237","DEMO_APP",System.getenv("DEMO_DB_PASSWORD"))) {
   c.setReadOnly(true);c.setAutoCommit(false);
   for(String table:CopyExistingBusinessData.TABLES) total+=export(c,table,sql,report);
   total+=export(c,"USERS",sql,report);c.rollback();
  }
  sql.append("SELECT setval(pg_get_serial_sequence('public.users','id'), GREATEST(COALESCE((SELECT MAX(id) FROM public.users),0),1), EXISTS(SELECT 1 FROM public.users));\nCOMMIT;\n");
  Path dir=Paths.get(args[0]);Files.createDirectories(dir);
  Files.write(dir.resolve("demo-postgres.sql"),sql.toString().getBytes(StandardCharsets.UTF_8));
  Files.write(dir.resolve("snapshot-report.md"),report.toString().getBytes(StandardCharsets.UTF_8));
  System.out.println("Exported 15 tables and "+total+" rows to private snapshot; source unchanged.");
 }
 static int export(Connection c,String table,StringBuilder sql,StringBuilder report) throws Exception {
  StringJoiner keys=new StringJoiner(",");
  try(ResultSet p=c.getMetaData().getPrimaryKeys(null,"DEMO_APP",table)){while(p.next())keys.add(q(p.getString("COLUMN_NAME")));}
  int count=0;
  try(Statement stmt=c.createStatement();ResultSet rows=stmt.executeQuery("SELECT * FROM DEMO_APP.\""+table+"\"")) {
   ResultSetMetaData m=rows.getMetaData();int n=m.getColumnCount();StringJoiner cols=new StringJoiner(","),definitions=new StringJoiner(",\n");
   for(int i=1;i<=n;i++) {
    String name=m.getColumnName(i);boolean identity="USERS".equals(table)&&"ID".equalsIgnoreCase(name);
    cols.add(q(name));definitions.add(q(name)+" "+type(m,i,identity)+(m.isNullable(i)==ResultSetMetaData.columnNoNulls?" NOT NULL":""));
   }
   if(keys.length()>0)definitions.add("PRIMARY KEY ("+keys+")");
   sql.append("CREATE TABLE public.").append(q(table)).append(" (\n").append(definitions).append("\n);\n");
   while(rows.next()) {
    StringJoiner values=new StringJoiner(",");for(int i=1;i<=n;i++)values.add(literal(rows,m,i));
    sql.append("INSERT INTO public.").append(q(table)).append(" (").append(cols).append(") VALUES (").append(values).append(");\n");count++;
   }
  }
  report.append(table).append(": ").append(count).append(" rows\n");return count;
 }
}
